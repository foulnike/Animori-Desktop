// 1.7467 выводит наибольший радиус на 18 единиц в квадрате 32; 1.2291 даёт 0.7038 (кнопка), 0.9075 — 0.52 (метка).
// Оба translate нужны, чтобы scale шёл от центра квадрата.
export function sakuraTurn(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(1.2291 1.7467) translate(-16 -16)`
}

/** Разворот лепестка для метки: узкие 0.52 с прорезями узнаются с 12 px; кнопочные сходились бы в пятно. */
export function sakuraTurnMark(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(0.9075 1.7467) translate(-16 -16)`
}

