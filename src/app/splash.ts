const PLAIN = 'С возвращением'

// Выбор один раз на запуск, а не на каждый приход на главную: экран монтируется заново,
// и без запоминания фраза менялась бы на глазах.
let chosen = ''

/** Фраза плашки на этот запуск. */
export function splashLine(): string {
  if (chosen === '') chosen = SPLASHES[Math.floor(Math.random() * SPLASHES.length)] ?? PLAIN
  return chosen
}
